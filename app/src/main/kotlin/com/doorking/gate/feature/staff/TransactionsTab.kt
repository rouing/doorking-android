private val MP4_EXT_REGEX = Regex("\\.mp4$", RegexOption.IGNORE_CASE)
private const val PORTAL_HOLD_MATCH_WINDOW_MS = 90_000L

/**
 * Formats the primary headline for a transaction card.
 * Shows "Entry Code · #<attemptedCode>" (or "<EventType> · #<number>") when there is no matched resident name/unit.
 */
fun formatTransactionHeadline(row: TransactionRowDto): String {
    val base = row.name.ifBlank { row.eventType.ifBlank { "Gate Event" } }
    return when {
        row.directoryCode.isNotBlank() -> "$base · #${row.directoryCode}"
        row.name.isBlank() && !row.number.isNullOrBlank() -> "$base · #${row.number}"
        else -> base
    }
}

private fun isPortalOpenRow(row: TransactionRowDto): Boolean =
    row.source.equals("portal", ignoreCase = true) ||
        row.eventType.equals("Portal Open", ignoreCase = true)

private fun relaysCompatible(a: String, b: String): Boolean {
    val na = a.trim().lowercase()
    val nb = b.trim().lowercase()
    return na.isEmpty() || nb.isEmpty() || na == nb
}

private fun withinPortalWindow(portal: TransactionRowDto, candidate: TransactionRowDto): Boolean {
    if (!relaysCompatible(portal.relay, candidate.relay)) return false
    if (portal.ts > 0L && candidate.ts > 0L) {
        return kotlin.math.abs(portal.ts - candidate.ts) <= PORTAL_HOLD_MATCH_WINDOW_MS
    }
    return portal.minute.isNotBlank() && portal.minute == candidate.minute
}

/**
 * Hides Hold Begin + Hold End rows generated by a Portal Open momentary buzz when BOTH Hold Begin
 * and Hold End match the Portal Open's time window and relay.
 */
fun hidePortalHoldNoise(rows: List<TransactionRowDto>): List<TransactionRowDto> {
    val portalIndices = rows.indices.filter { isPortalOpenRow(rows[it]) }
    if (portalIndices.isEmpty()) return rows

    val hiddenIndices = mutableSetOf<Int>()
    for (pIdx in portalIndices) {
        val portal = rows[pIdx]
        val beginIdx = rows.indices.firstOrNull { i ->
            i !in hiddenIndices &&
                rows[i].eventType.equals("Hold Begin", ignoreCase = true) &&
                withinPortalWindow(portal, rows[i])
        } ?: continue
        val endIdx = rows.indices.firstOrNull { i ->
            i !in hiddenIndices &&
                rows[i].eventType.equals("Hold End", ignoreCase = true) &&
                withinPortalWindow(portal, rows[i]) &&
                (rows[beginIdx].ts <= 0L || rows[i].ts <= 0L ||
                    kotlin.math.abs(rows[i].ts - rows[beginIdx].ts) <= PORTAL_HOLD_MATCH_WINDOW_MS)
        } ?: continue
        hiddenIndices.add(beginIdx)
        hiddenIndices.add(endIdx)
    }
    if (hiddenIndices.isEmpty()) return rows
    return rows.filterIndexed { idx, _ -> idx !in hiddenIndices }
}

private data class KeyedTransaction(
    val key: String,
    val row: TransactionRowDto,
)

private fun keyTransactions(rows: List<TransactionRowDto>): List<KeyedTransaction> {
    val seen = HashMap<String, Int>(rows.size)
    return rows.map { row ->
        val baseKey = "${row.source ?: "gate"}-${row.txKey ?: "${row.ts}-${row.raw}-${row.directoryCode}"}"
        val occurrence = seen[baseKey] ?: 0
        seen[baseKey] = occurrence + 1
        val uniqueKey = if (occurrence == 0) baseKey else "$baseKey#$occurrence"
        KeyedTransaction(key = uniqueKey, row = row)
    }
}

private fun hasReadyMedia(snap: SnapshotMinuteDto?, isVideoMode: Boolean): Boolean {
    val files = snap?.takeIf { it.status != "removed" }?.files ?: return false
    if (files.isEmpty()) return false
    return if (isVideoMode) {
        files.any { it.endsWith(".mp4", ignoreCase = true) }
    } else {
        true
    }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
fun TransactionsTab(
    state: StaffGateUiState,
    serverUrl: String,
    gatePhone: String,
    okHttpClient: OkHttpClient,
    onLoadOlder: () -> Unit,
    onRequestSnapshot: (minute: String) -> Unit,
    onStopSnapshots: () -> Unit = {},
) {
    var query by remember { mutableStateOf("") }
    var viewing by remember { mutableStateOf<Pair<TransactionRowDto, List<MediaItemEntry>>?>(null) }

    val visible = remember(state.visibleTransactions, state.transactions) {
        val rows = if (state.visibleTransactions.isNotEmpty() || state.transactions.isEmpty()) {
            state.visibleTransactions
        } else {
            hidePortalHoldNoise(state.transactions)
        }
        keyTransactions(rows)
    }
    val filtered = remember(visible, query) {
        val q = query.trim().lowercase()
        if (q.isEmpty()) {
            visible
        } else {
            visible.filter { (_, r) ->
                r.name.lowercase().contains(q) ||
                    r.eventType.lowercase().contains(q) ||
                    r.access.lowercase().contains(q) ||
                    r.directoryCode.lowercase().contains(q) ||
                    r.number.orEmpty().contains(q) ||
                    r.date.contains(q)
            }
        }
    }

    if (viewing != null) {
        val (tx, items) = viewing!!
        MediaViewerDialog(
            title = tx.name.ifBlank { tx.eventType.ifBlank { "Gate Event" } },
            subtitle = "${tx.date} ${tx.time} · ${tx.eventType} ${tx.access}".trim(),
            items = items,
            okHttpClient = okHttpClient,
            onDismiss = { viewing = null },
        )
    }

    val hasCamera = state.cameras != null
    val isVideoMode = state.cameras?.mode == "video"
    val base = serverUrl.trimEnd('/')

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = 12.dp, bottom = 24.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        if (state.error != null) {
            item(key = "error", contentType = "error") { ErrorBanner(state.error) }
        }

        item(key = "search", contentType = "search") {
            SearchPillBar(
                query = query,
                onQueryChange = { query = it },
                placeholder = "Search transactions",
            )
        }

        val activeRun = state.snapRun
        if (hasCamera && activeRun?.state == "running") {
            item(key = "camera-run", contentType = "camera_run") {
                val prog = activeRun.progress
                val kindLabel = if (isVideoMode) "videos" else "snapshots"
                val progressText = when {
                    activeRun.stopping -> "Stopping camera $kindLabel…"
                    prog != null && prog.frames > 0 -> "Downloading camera $kindLabel (${prog.framesDone}/${prog.frames})…"
                    prog != null && prog.minutes > 0 -> "Downloading camera $kindLabel (${prog.minutesDone}/${prog.minutes})…"
                    else -> "Downloading camera $kindLabel…"
                }
                BubbleCard(containerColor = MaterialTheme.colorScheme.surfaceContainerHigh) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(10.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Column(
                            modifier = Modifier.weight(1f),
                            verticalArrangement = Arrangement.spacedBy(6.dp),
                        ) {
                            Text(progressText, style = MaterialTheme.typography.titleSmall)
                            if (prog != null && prog.frames > 0) {
                                LinearProgressIndicator(
                                    progress = { (prog.framesDone.toFloat() / prog.frames.toFloat()).coerceIn(0f, 1f) },
                                    modifier = Modifier.fillMaxWidth(),
                                )
                            } else {
                                LinearProgressIndicator(modifier = Modifier.fillMaxWidth())
                            }
                        }
                        Button(
                            enabled = !activeRun.stopping,
                            onClick = onStopSnapshots,
                            colors = ButtonDefaults.buttonColors(
                                containerColor = MaterialTheme.colorScheme.error,
                                contentColor = MaterialTheme.colorScheme.onError,
                            ),
                            contentPadding = PaddingValues(horizontal = 12.dp, vertical = 6.dp),
                        ) {
                            Icon(Icons.Rounded.Stop, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(Modifier.width(4.dp))
                            Text("Stop")
                        }
                    }
                }
            }
        }

        if (filtered.isEmpty()) {
            item(key = "empty", contentType = "empty") {
                BubbleCard {
                    Text("No transactions", style = MaterialTheme.typography.titleMedium)
                    Text(
                        text = "Open the Gate tab and tap Pull transactions to download recent gate events.",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        } else {
            items(
                items = filtered,
                key = { it.key },
                contentType = { (_, row) ->
                    when {
                        hasReadyMedia(state.snapshots[row.minute], isVideoMode) -> "tx_media"
                        hasCamera && row.camera && row.minute.isNotBlank() -> "tx_action"
                        else -> "tx_plain"
                    }
                },
            ) { (_, row) ->
                val activeSnap = state.snapshots[row.minute]?.takeIf { it.status != "removed" }
                val allFiles = activeSnap?.files.orEmpty()
                val hasVideoFile = allFiles.any { it.endsWith(".mp4", ignoreCase = true) }
                val hasReadyMedia = allFiles.isNotEmpty() && (!isVideoMode || hasVideoFile)
                val thumbUrl = if (hasReadyMedia) {
                    remember(row.minute, allFiles, hasVideoFile, base, gatePhone) {
                        if (hasVideoFile) {
                            val firstMp4 = allFiles.firstOrNull { it.endsWith(".mp4", ignoreCase = true) }
                            firstMp4?.let { mp4 ->
                                val poster = mp4.replace(MP4_EXT_REGEX, ".jpg")
                                "$base/api/gates/$gatePhone/snapshots/${row.minute}/$poster"
                            }
                        } else {
                            allFiles.firstOrNull { it.endsWith(".jpg", ignoreCase = true) }?.let { jpg ->
                                "$base/api/gates/$gatePhone/snapshots/${row.minute}/$jpg"
                            }
                        }
                    }
                } else {
                    null
                }

                val accessTone = when {
                    row.access.contains("Deny", ignoreCase = true) -> PillTone.Error
                    row.access.contains("Admit", ignoreCase = true) -> PillTone.Success
                    row.eventType.contains("Hold", ignoreCase = true) -> PillTone.Warning
                    else -> PillTone.Neutral
                }

                BubbleCard {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Column(
                            modifier = Modifier.weight(1f),
                            verticalArrangement = Arrangement.spacedBy(6.dp),
                        ) {
                            val headline = formatTransactionHeadline(row)
                            Text(text = headline, style = MaterialTheme.typography.titleSmall)
                            FlowRow(
                                horizontalArrangement = Arrangement.spacedBy(6.dp),
                                verticalArrangement = Arrangement.spacedBy(6.dp),
                            ) {
                                val combined = listOf(row.eventType, row.access)
                                    .filter { it.isNotBlank() }
                                    .joinToString(" · ")
                                if (combined.isNotBlank()) {
                                    StatusPill(text = combined, tone = accessTone)
                                }
                                StatusPill(text = "${row.date} ${row.time}".trim(), tone = PillTone.Neutral)
                                if (row.relay.isNotBlank()) {
                                    val resolved = state.prefs.relayLabels[row.relay]
                                        ?: row.relay.trim().removePrefix("Relay ").removePrefix("relay ").trim()
                                    val formatted = resolved.replaceFirstChar {
                                        if (it.isLowerCase()) it.titlecase() else it.toString()
                                    }
                                    StatusPill(text = "Relay · $formatted", tone = PillTone.Primary)
                                }
                            }
                        }

                        // Right-aligned camera thumbnail (uses ch<N>.jpg poster for .mp4 clips) or Get video button.
                        if (hasReadyMedia) {
                            Box(
                                modifier = Modifier
                                    .size(width = 80.dp, height = 54.dp)
                                    .clip(RoundedCornerShape(12.dp))
                                    .background(MaterialTheme.colorScheme.surfaceContainerHighest)
                                    .clickable(
                                        role = Role.Button,
                                        onClickLabel = if (hasVideoFile) "Play gate video" else "View gate snapshot",
                                    ) {
                                        val displayFiles = if (isVideoMode && hasVideoFile) {
                                            allFiles.filter { it.endsWith(".mp4", ignoreCase = true) }
                                        } else {
                                            allFiles
                                        }
                                        val mediaEntries = displayFiles.map { file ->
                                            MediaItemEntry(
                                                label = file.substringBefore('.').uppercase(),
                                                url = "$base/api/gates/$gatePhone/snapshots/${row.minute}/$file",
                                                isVideo = file.endsWith(".mp4", ignoreCase = true),
                                            )
                                        }
                                        viewing = row to mediaEntries
                                    },
                                contentAlignment = Alignment.Center,
                            ) {
                                if (thumbUrl != null) {
                                    AsyncImage(
                                        model = thumbUrl,
                                        contentDescription = null,
                                        contentScale = ContentScale.Crop,
                                        modifier = Modifier.matchParentSize(),
                                    )
                                }
                                if (hasVideoFile) {
                                    Box(
                                        modifier = Modifier
                                            .size(28.dp)
                                            .clip(CircleShape)
                                            .background(MaterialTheme.colorScheme.scrim.copy(alpha = 0.68f)),
                                        contentAlignment = Alignment.Center,
                                    ) {
                                        Icon(
                                            imageVector = Icons.Rounded.PlayArrow,
                                            contentDescription = null,
                                            tint = Color.White,
                                            modifier = Modifier.size(18.dp),
                                        )
                                    }
                                }
                            }
                        } else if (hasCamera && row.camera && row.minute.isNotBlank()) {
                            FilledTonalButton(
                                onClick = { onRequestSnapshot(row.minute) },
                                contentPadding = PaddingValues(horizontal = 12.dp, vertical = 6.dp),
                            ) {
                                Icon(Icons.Rounded.Videocam, contentDescription = null, modifier = Modifier.size(16.dp))
                                Spacer(Modifier.width(4.dp))
                                Text(
                                    text = if (isVideoMode) "Get video" else "Get snap",
                                    style = MaterialTheme.typography.labelMedium,
                                )
                            }
                        }
                    }
                }
            }

            if (state.txNextBefore != null) {
                item(key = "more", contentType = "load_more") {
                    FilledTonalButton(
                        onClick = onLoadOlder,
                        enabled = !state.loadingOlderTx,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(if (state.loadingOlderTx) "Loading older…" else "Load older transactions")
                    }
                }
            }
        }
    }
}
